function band(locale: NewsletterEmailLocale, key: BandKey, extra = ''): string {
  const alt = BAND_ALT[locale][key]
  return `<img src="${SITE_URL}${EMAIL_BANDS[key]}" width="520" alt="${escapeHtml(
    alt
  )}" style="display:block;width:100%;max-width:520px;height:auto;border:0;${extra}" />`
}

const P = 'color:#5C4A3A;font-size:15px;line-height:1.6;margin:0 0 20px;'

export function button(href: string, label: string): string {
  return `
    <table role="presentation" cellpadding="0" cellspacing="0" style="margin:0 0 16px;">
      <tr>
        <td bgcolor="#0C3C2D" style="background:#0C3C2D;">
          <a href="${escapeHtml(href)}" style="display:inline-block;padding:16px 32px;color:#FAF0E6;font-size:14px;text-transform:uppercase;letter-spacing:2px;text-decoration:none;">${escapeHtml(label)}</a>
        </td>
      </tr>
    </table>`
}

export function paragraph(text: string, style = P): string {
  return `<p style="${style}">${escapeHtml(text)}</p>`
}

export interface ShellOptions {
  locale: NewsletterEmailLocale
  title: string
  preview: string
  bodyHtml: string
  /** Optional photo strip after the divider. */
  photo?: 'dish' | 'table'
  unsubscribeUrl: string
}

/** Header band, brand text, body, divider band, optional photo band, footer. */
