const CONFIRM_COPY = {
  fr: {
    subject: 'Confirmez votre inscription à Gecko Cabane',
    reason: 'Vous avez demandé à recevoir la newsletter de Gecko Cabane.',
  },
  en: {
    subject: 'Confirm your Gecko Cabane subscription',
    reason: 'You asked to receive the Gecko Cabane newsletter.',
  },
} as const

export function newsletterConfirmEmail(
  locale: NewsletterEmailLocale,
  urls: { confirm: string; unsubscribe: string }
): NewsletterEmail {
  const c = COMMON[locale]
  const k = CONFIRM_COPY[locale]
  const body =
    paragraph(k.reason) +
    button(urls.confirm, c.cta) +
    paragraph(`${c.fallback}${urls.confirm}`, 'color:#5C4A3A;font-size:14px;font-style:italic;line-height:1.5;margin:0 0 12px;word-break:break-all;') +
    paragraph(c.expiry, 'color:#5C4A3A;font-size:13px;margin:0 0 8px;') +
    paragraph(c.ignore, 'color:#5C4A3A;font-size:13px;margin:0 0 16px;')
  const html = newsletterShell({
    locale,
    title: k.subject,
    preview: k.reason,
    bodyHtml: body,
    unsubscribeUrl: urls.unsubscribe,
  })
  const text = [k.reason, `${c.cta}: ${urls.confirm}`, c.expiry, c.ignore, `${c.unsubscribe}: ${urls.unsubscribe}`, c.legal].join('\n\n')
  return { subject: stripLineBreaks(k.subject), html, text }
}

