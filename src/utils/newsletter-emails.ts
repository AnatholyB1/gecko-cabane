/** Campaign kinds count against the 1 email per month cap (D-08); J+2/J+3 do not. */
export const CAMPAIGN_KINDS: readonly SequenceKind[] = ['october_return', 'green_season']

export function sequenceEmail(
  kind: SequenceKind,
  locale: NewsletterEmailLocale,
  unsubscribeUrl: string
): NewsletterEmail {
  const c = SEQUENCE_COPY[kind][locale]
  const common = COMMON[locale]
  const base = `${SITE_URL}/${locale}`
  const noteHtml = c.note
    ? `<p style="color:#5C4A3A;font-size:14px;line-height:1.5;margin:8px 0 16px;">${escapeHtml(
        c.note.text
      )}<a href="${escapeHtml(base + c.note.path)}" style="color:#0C3C2D;">${escapeHtml(c.note.linkLabel)}</a></p>`
    : ''
  const body =
    c.paragraphs.map((p) => paragraph(p)).join('') +
    c.buttons.map((b) => button(base + b.path, b.label)).join('') +
    noteHtml +
    paragraph(c.signoff, 'color:#5C4A3A;font-size:14px;font-style:italic;line-height:1.5;margin:8px 0 16px;')
  const html = newsletterShell({
    locale,
    title: c.subject,
    preview: c.preview,
    bodyHtml: body,
    photo: c.photo,
    unsubscribeUrl,
  })
  const text = [
    ...c.paragraphs,
    ...c.buttons.map((b) => `${b.label}: ${base}${b.path}`),
    c.note ? `${c.note.text}${base}${c.note.path}` : null,
    c.signoff,
    `${common.unsubscribe}: ${unsubscribeUrl}`,
    common.legal,
  ]
    .filter((s): s is string => s !== null)
    .join('\n\n')
  return { subject: stripLineBreaks(c.subject), html, text }
}
